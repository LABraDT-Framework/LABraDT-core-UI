(function(root){
 'use strict';
 const clone=value=>JSON.parse(JSON.stringify(value));
 async function request(path,method='GET',body,headers={}){
  const response=await root.GucEnvironment.fetch(path,{method,headers:{'Content-Type':'application/json',...headers},...(body===undefined?{}:{body:JSON.stringify(body)})});
  const raw=await response.text();let value;try{value=raw?JSON.parse(raw):null;}catch{value=raw;}
  if(!response.ok)throw Error(typeof value?.detail==='string'?value.detail:value?.detail?.message||JSON.stringify(value?.detail||value));
  return value;
 }
 function create({onAas,onServices,onRules,toast}){
  let workspace={revision:0,services:{},rules:[],states:{}}, aas=[], registry=[], loaded=false, aasLoaded=false, busy=false, refreshing=null, lastError='', status={};
  const path=(kind,id)=>'/api/aas/models/'+kind+(id?'?identifier='+encodeURIComponent(id):'');
  function normalized(environment){return environment.assetAdministrationShells.length?root.GucAasTemplates.normalizeImport(environment):[];}
  function publish(){onAas(clone(aas));onServices(registry,workspace.services);onRules?.(workspace.rules,workspace.states);}
  async function refresh(force=false){
   if(busy)return;if(refreshing)return refreshing;
   if(!force && (document.querySelector('dialog[open],.modal-backdrop.open') || document.activeElement?.closest('#serviceDetailSection')))return;
   refreshing=(async()=>{
    // The parts load independently: the Service Manager and the workspace work without an AAS repository.
    // Saved changes always land in the projects; the status says whether they also reached the running servers.
    const [models,definitions,metadata,live]=await Promise.allSettled([request('/api/aas/environment'),request('/api/services/registry'),request('/api/workspace'),request('/api/project/status')]);
    if(live.status==='fulfilled'){const changed=JSON.stringify(status)!==JSON.stringify(live.value);status=live.value;root.gucProjectStatus=status;if(changed){if(typeof root.CustomEvent==='function'&&root.dispatchEvent)root.dispatchEvent(new root.CustomEvent('labradt:project-status',{detail:status}));force=true;}}
    const errors=[];
    if(definitions.status==='fulfilled'&&metadata.status==='fulfilled'){
     const servicesChanged=JSON.stringify([registry,workspace.services])!==JSON.stringify([definitions.value,metadata.value.services]);
     registry=definitions.value;workspace=metadata.value;loaded=true;
     if(servicesChanged||force)onServices(registry,workspace.services);
     onRules?.(workspace.rules,workspace.states);
    } else errors.push((definitions.reason||metadata.reason).message);
    if(models.status==='fulfilled'){
     const nextAas=normalized(models.value), aasChanged=JSON.stringify(aas)!==JSON.stringify(nextAas);
     aas=nextAas;aasLoaded=true;
     if(aasChanged||force)onAas(clone(aas));
    } else errors.push(models.reason.message);
    const message=errors.join(' · ');
    if(message&&message!==lastError)toast('Backend: '+message);
    lastError=message;
   })().finally(()=>refreshing=null);return refreshing;
  }
  async function saveModel(kind,model,old){
   if(!old)return request(path(kind),'POST',model);
   if(JSON.stringify(model)===JSON.stringify(old))return;
   const response=await root.GucEnvironment.fetch(path(kind,model.id));
   if(!response.ok)throw Error('Repository model is unavailable. Refresh before saving.');
   const current=await response.json();
   // Compare the normalized representation, not live CPS metadata regenerated by Engine.
   if(JSON.stringify(current)!==JSON.stringify(old))throw Error('Repository model changed. Refresh and reopen the form.');
   return request(path(kind,model.id),'PUT',model,{'If-Match':response.headers.get('ETag')});
  }
  async function saveAas(items){
   if(!aasLoaded)throw Error('The AAS repository (port 8081) is not reachable.');busy=true;
   try{
    const oldModels=aas.flatMap(item=>{const env=root.GucAasTemplates.toAasEnvironment(item);return [...env.submodels,...env.assetAdministrationShells];});
    const newModels=items.flatMap(item=>{const env=root.GucAasTemplates.toAasEnvironment(item);return [...env.submodels,...env.assetAdministrationShells];});
    // Shared Submodels are written once; their global identity is never changed on edit.
    const written=new Set();
    for(const item of newModels){
     if(written.has(item.id))continue;written.add(item.id);
     const old=oldModels.find(model=>model.id===item.id), kind=item.modelType==='Submodel'?'submodels':'shells';
     if(old&&JSON.stringify(item)===JSON.stringify(old))continue;
     // Raw server snapshots retain fields not exposed by the common editor.
     const raw=aas.flatMap(a=>[a,...a.submodels]).find(a=>a.identifier===item.id)?._raw;
     await saveModel(kind,item,old?raw:undefined);
    }
    for(const item of aas.filter(old=>!items.some(next=>next.identifier===old.identifier)))await request(path('shells',item.identifier),'DELETE');
   }finally{busy=false;await refresh(true);}
  }
  async function saveWorkspace(patch){
   if(!loaded)throw Error('Wait for Backend workspace to load.');
   const next=await request('/api/workspace','PUT',{revision:workspace.revision,services:workspace.services,rules:workspace.rules,...patch});workspace=next;return next;
  }
  async function deleteSubmodel(identifier){
   if(!aasLoaded)throw Error('The AAS repository (port 8081) is not reachable.');
   if(busy)throw Error('Wait for the current Backend change to finish.');
   if(refreshing)await refreshing;
   busy=true;
   try{
    const [links,metadata]=await Promise.all([request('/api/bindings'),request('/api/workspace')]);
    const usesProperty=id=>{
     if(typeof id!=='string')return false;
     try{return decodeURIComponent(id.split('|')[1]||'')===identifier;}catch{return false;}
    };
    const usedByRules=metadata.rules.some(rule=>(rule.monitors||[]).some(item=>usesProperty(item.propertyId))||usesProperty(rule.output?.propertyId)||Object.values(rule.serviceCall?.bindings||{}).some(item=>usesProperty(item.propertyId)));
    if(links.bindings.some(item=>item.submodelId===identifier)||usedByRules)throw Error('This Submodel is used by Gateway bindings or Rules. Remove those links before deleting it.');
    await request(path('submodels',identifier),'DELETE');
   }finally{busy=false;await refresh(true);}
  }
  async function saveServices(items){
   if(!loaded)throw Error('Wait for Backend Service Manager to load.');busy=true;
   try{
    const metadata=Object.fromEntries(items.map(item=>[item.id,clone(item)]));
    // Save UI-only operation descriptions before removing referenced definitions.
    await saveWorkspace({services:metadata});
    for(const item of items){
     const args=JSON.parse(item.defaultArgs||'{}');
     const body={serviceId:item.id,displayName:item.name,description:item.description||'',executionCategory:item.category,technologyAdapter:item.adapter,fileReference:item.file==='[inline Lua]'||String(item.file||'').startsWith('[image]')?'':item.file,defaultArgs:Object.fromEntries(Object.entries(args).map(([key,value])=>[key,typeof value==='object'?JSON.stringify(value):String(value)]))};
     const old=registry.find(record=>record.serviceId===item.id);
     const same=old&&Object.keys(body).every(key=>JSON.stringify(body[key])===JSON.stringify(old[key]));
     if(!same)await request('/api/services/registry'+(old?'/'+encodeURIComponent(item.id):''),old?'PUT':'POST',body);
    }
    for(const item of registry.filter(old=>!items.some(next=>next.id===old.serviceId)))await request('/api/services/registry/'+encodeURIComponent(item.serviceId),'DELETE');
   }finally{busy=false;await refresh(true);}
  }
  async function writeProperty(property,value){await request('/api/aas/value?submodelId='+encodeURIComponent(property.submodelId)+'&idShortPath='+encodeURIComponent(property.path),'PATCH',value);await refresh(true);}
  async function testRule(rule){const result=await request('/api/workspace/test','POST',{rule});await refresh(true);if(result.status==='Failed')throw Error(result.message);return result;}
  function start(){refresh();const timer=root.setInterval(refresh,2500);root.addEventListener('pagehide',()=>root.clearInterval(timer),{once:true});}
  return {start,refresh,saveAas,deleteSubmodel,saveServices,writeProperty,saveRules:rules=>saveWorkspace({rules}),testRule,request};
 }
 root.GucBackendWorkspace={create,request};
})(window);
